"""LongMemEval real comparison: Mnemosis vs mem0 official package.

Uses the official LongMemEval-S cleaned dataset (longmemeval_s_cleaned.json):
~40 sessions / ~115k tokens of chat history per question, i.e. long text with
heavy interference. Every question gets a fresh store for each system; both
systems ingest the identical turns (mem0 with Ollama embeddings + Chroma,
infer=False; Mnemosis with keyword / ngram retrieval). Retrieval is scored by
turn-level recall (has_answer turns) and by whether the gold answer tokens
appear in top-K. Answers are generated by qwen3.7-plus using only the top-5
retrieved memories, then judged by qwen3.7-plus against the gold answer.

Run with the Python that has mem0 installed, e.g.:
    C:\\Python314\\python.exe benchmarks/longmemeval_bench.py \
        --data work/longmemeval_s_cleaned.json --questions 20
"""

