LOCAL_MODEL = "qwen2.5:3b"
STRONG_LOCAL_MODEL = "gemma3:12b"

_ABBREVIATIONS = (
    "mr.", "mrs.", "ms.", "dr.", "prof.", "st.", "vs.", "e.g.", "i.e.",
    "u.s.", "u.k.", "etc.", "inc.", "ltd.", "jr.", "sr.",
)


def segment_text(text: str, min_len: int = 40, max_segments: int = 4) -> list[str]:
    """Split a long turn into sentence-level memories (value granularity).

    Short turns stay whole; long turns contribute at most ``max_segments``
    sentences so the segment index stays lightweight.
    """
    if len(text) < min_len * 2:
        return [text]
    protected = text
    for abbreviation in _ABBREVIATIONS:
        protected = re.sub(
            re.escape(abbreviation),
            lambda match: match.group(0).replace(".", "<DOT>"),
            protected,
            flags=re.IGNORECASE,
        )
    parts = re.split(
        r"(?<=[.!?])\s+(?=[A-Z0-9\"'(])|\n+",
        protected.strip(),
    )
    out = []
    for part in parts:
        part = part.replace("<DOT>", ".").strip()
        if len(part) >= min_len:
            out.append(part)
        if len(out) >= max_segments:
            break
    if not out:
        return [text]
    return out


def _tokens(text: str) -> list[str]:
    return re.findall(r"[a-z0-9']+", text.lower())


def _answer_hit(content: str, expected: list[str]) -> bool:
    lowered = content.lower()
    return all(token in lowered for token in expected)


def local_generate(
    prompt: str, model: str = LOCAL_MODEL, max_tokens: int = 300
) -> str:
    payload = {
        "model": model,
        "messages": [{"role": "user", "content": prompt}],
        "temperature": 0,
        "max_tokens": max_tokens,
    }
    req = urllib.request.Request(
        OLLAMA_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=300) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        content = data["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError, json.JSONDecodeError) as exc:
        raise RuntimeError(
            f"unexpected Ollama response for {model}: {exc}"
        ) from exc
    return content.strip()


def judge_local(question: str, gold: str, candidate: str) -> bool:
    """Local LLM judge (gemma3:12b) - no cloud involved."""
    prompt = (
        "You are a strict evaluator. Decide whether the model answer is "
        "correct given the question and the ground-truth answer. "
        "If the ground truth says the information is NOT available, a "
        "correct model answer must say it cannot answer or give the "
        "ground-truth value (e.g. 0).\n"
        f"Question: {question}\n"
        f"Ground truth: {gold}\n"
        f"Model answer: {candidate}\n"
        "Reply with exactly one token: 1 if correct, 0 if incorrect."
    )
    try:
        verdict = local_generate(prompt, model=STRONG_LOCAL_MODEL, max_tokens=10)
    except Exception as exc:  # noqa: BLE001
        print(f"    judge_local failed: {exc}", flush=True)
        return False
    match = re.search(r"\b([01])\b", verdict)
    return bool(match and match.group(1) == "1")


def judge_local_strict(question: str, gold: str, candidate: str) -> bool:
    """Strict local judge: 'unknown' is wrong when the gold has an answer."""
    candidate = _extract_final_answer(candidate)
    prompt = (
        "You are a STRICT evaluator. The ground-truth answer is definitive. "
        "If the model answer is 'unknown' or says it cannot answer, but the "
        "ground truth contains a concrete answer, mark 0. Only accept "
        "'unknown' when the ground truth itself says the information is not "
        "available or is 'unknown'.\n"
        f"Question: {question}\n"
        f"Ground truth: {gold}\n"
        f"Model answer: {candidate}\n"
        "Reply with exactly one token: 1 if correct, 0 if incorrect."
    )
    try:
        verdict = local_generate(prompt, model=STRONG_LOCAL_MODEL, max_tokens=10)
    except Exception as exc:  # noqa: BLE001
        print(f"    judge_local_strict failed: {exc}", flush=True)
        return False
    match = re.search(r"\b([01])\b", verdict)
    return bool(match and match.group(1) == "1")


def keyword_correct(question: str, gold: str, candidate: str) -> bool:
    """Rule-based fallback: all gold tokens appear in the candidate."""
    gold_tokens = _tokens(gold)
    if not gold_tokens:
        return False
    candidate_tokens = set(_tokens(candidate))
    return all(token in candidate_tokens for token in gold_tokens)


def _extract_final_answer(text: str) -> str:
    """Pull the ANSWER: line out of a reasoning-chain response."""
    match = re.search(r"ANSWER:\s*([^\n]+)", text, flags=re.IGNORECASE)
    # No ANSWER: line -> empty, so reasoning text can never leak into the
    # judge and inflate the score.
    return match.group(1).strip() if match else ""


def make_nomic_embedder(cache_path: str | None = None):
    """Wrap Ollama nomic-embed-text (same embedder mem0 uses) as an Embedder."""
    from mnemosis.embedding import CallableEmbedder
    from mnemosis.embedding_cache import SqliteEmbeddingCache

    def _embed(text: str) -> list[float]:
        last = None
        for attempt in range(3):
            try:
                payload = {"model": "nomic-embed-text", "input": text}
                req = urllib.request.Request(
                    OLLAMA_EMBED_URL,
                    data=json.dumps(payload).encode("utf-8"),
                    headers={"Content-Type": "application/json"},
                )
                with urllib.request.urlopen(req, timeout=180) as resp:
                    data = json.loads(resp.read().decode("utf-8"))
                return data["embeddings"][0]
            except Exception as exc:  # noqa: BLE001
                last = exc
                time.sleep(min(2 ** (attempt + 1), 30) + random.uniform(0, 1))
        raise RuntimeError(f"embed failed after 3 attempts: {last}")

    if cache_path:
        os.makedirs(os.path.dirname(cache_path), exist_ok=True)
        return SqliteEmbeddingCache(CallableEmbedder(_embed), cache_path)
    from functools import lru_cache

    @lru_cache(maxsize=20000)
    def _embed_cached(text: str) -> tuple[float, ...]:
        return tuple(_embed(text))

    return CallableEmbedder(lambda text: list(_embed_cached(text)))


def _cloud_with_retry(prompt: str, max_tokens: int, attempts: int = 3) -> str:
    last = None
    for index in range(attempts):
        try:
            return cloud_generate(prompt, max_tokens=max_tokens)
        except Exception as exc:  # noqa: BLE001
            last = exc
            print(f"    cloud retry {index + 1}/{attempts}: {exc}", flush=True)
            time.sleep(min(2 ** (index + 1), 30) + random.uniform(0, 1))
    raise RuntimeError(f"cloud_generate failed after {attempts} attempts: {last}")


def _local_with_retry(
    prompt: str, model: str = LOCAL_MODEL, attempts: int = 3
) -> str:
    last = None
    for index in range(attempts):
        try:
            return local_generate(prompt, model=model)
        except Exception as exc:  # noqa: BLE001
            last = exc
            print(f"    local retry {index + 1}/{attempts}: {exc}", flush=True)
            time.sleep(min(2 ** (index + 1), 30) + random.uniform(0, 1))
    raise RuntimeError(f"local_generate failed after {attempts} attempts: {last}")


def judge_answer(question: str, gold: str, candidate: str) -> bool:
    candidate = _extract_final_answer(candidate)
    gold_lower = gold.lower().strip()
    abstain = any(
        keyword in gold_lower
        for keyword in (
            "unknown", "not mentioned", "not available", "n/a",
            "unable to answer", "cannot be determined", "not discussed",
            "no information",
        )
    )
    prompt = (
        "You are an evaluator. Decide whether the model answer is correct "
        "given the question and the ground-truth answer.\n"
        f"Question: {question}\n"
        f"Ground truth: {gold}\n"
        f"Model answer: {candidate}\n"
    )
    if abstain:
        prompt += (
            "The ground truth says the information is NOT available, so a "
            "correct model answer must say it cannot answer / does not know. "
        )
    prompt += (
        "Reply with exactly one token: 1 if correct, 0 if incorrect."
    )
    verdict = _cloud_with_retry(prompt, max_tokens=10).strip().lower()
    match = re.search(r"\b([01])\b", verdict)
    return bool(match and match.group(1) == "1")


def answer_prompt(contents: list[str], question: str) -> str:
    context = "\n".join(f"- {c}" for c in contents)
    return _temporal_reasoning_prompt(context, question, "")


def answer_prompt_local(
    contents: list[str], question: str, question_date: str = ""
) -> str:
    """Local-friendly prompt: explicit instructions, optional question date."""
    context = "\n".join(f"- {c}" for c in contents)
    date_line = f"\nToday's date: {question_date}" if question_date else ""
    return _temporal_reasoning_prompt(context, question, date_line)


def _temporal_reasoning_prompt(
    context: str, question: str, date_line: str
) -> str:
    """Structured temporal-reasoning chain for long multi-session context.

    Bad-case analysis (30 LongMemEval questions, cloud Qwen judging) showed
    errors concentrate on multi-session aggregation, temporal reasoning and
    knowledge updates. This prompt forces the model to (1) build a
    chronological timeline, (2) aggregate when asked for totals, (3) prefer
    the most recent fact on conflict, and (4) emit one final ANSWER line so
    judges are not confused by the reasoning.
    """
    return (
        "Answer using ONLY the memory context below. Reason step by step:\n"
        "1) Build a timeline: list every dated fact in chronological order "
        "as 'date -> fact'.\n"
        "2) If the question asks for a total / sum / how much in total, "
        "identify all relevant amounts and add them up.\n"
        "3) If different facts conflict, the one with the most recent date "
        "wins; older values are superseded (knowledge updates).\n"
        "4) If the context does not contain the answer, answer exactly "
        "'unknown'.\n"
        "Then output your FINAL ANSWER on its own line prefixed with "
        "'ANSWER:' followed by exactly one line (no newline inside the "
        "answer, no extra text after it).\n\n"
        f"Context:\n{context}\n"
        f"{date_line}\n"
        f"Question: {question}"
    )


def _fresh_mem0(db_dir: str, collection: str):
    from mem0 import Memory

    if os.path.isdir(db_dir):
        shutil.rmtree(db_dir)
    cfg = {
        "llm": {
            "provider": "ollama",
            "config": {
                "model": LOCAL_MODEL,
                "ollama_base_url": "http://127.0.0.1:11434",
                "temperature": 0,
                "max_tokens": 500,
            },
        },
        "embedder": {
            "provider": "ollama",
            "config": {
                "model": "nomic-embed-text",
                "ollama_base_url": "http://127.0.0.1:11434",
            },
        },
        "vector_store": {
            "provider": "chroma",
            "config": {
                "collection_name": collection,
                "path": db_dir,
            },
        },
        "history_db_path": os.path.join(db_dir, "history.db"),
    }
    return Memory.from_config(cfg)


def run_system_mem0(question: dict, qid: str, top_k: int, workdir: str) -> dict:
    db_dir = os.path.join(workdir, "mem0", qid)
    mem = _fresh_mem0(db_dir, f"lme_{qid[:12]}")
    user_id = "u1"
    has_answer_contents: set[str] = set()
    all_contents: set[str] = set()
    turns = 0
    t0 = time.perf_counter()
    for session in question["haystack_sessions"]:
        for turn in session:
            content = turn.get("content", "")
            if not content:
                continue
            mem.add(content, user_id=user_id, infer=False)
            turns += 1
            all_contents.add(content)
            if turn.get("has_answer"):
                has_answer_contents.add(content)
    ingest = time.perf_counter() - t0

    t0 = time.perf_counter()
    try:
        resp = mem.search(
            question["question"], filters={"user_id": user_id}, limit=top_k
        )
    except TypeError:
        resp = mem.search(question["question"], user_id=user_id, limit=top_k)
    search = time.perf_counter() - t0
    contents = []
    for entry in resp.get("results", []) if isinstance(resp, dict) else resp:
        text = entry.get("memory") or entry.get("text") or "" if isinstance(entry, dict) else str(entry)
        if text:
            contents.append(text)
    del mem
    return {
        "turns": turns,
        "ingest_seconds": round(ingest, 2),
        "search_ms": round(search * 1000, 1),
        "contents": contents,
        "evidence_hits": sum(1 for c in contents if c in has_answer_contents or any(c in h for h in has_answer_contents)),
        "evidence_total": len(has_answer_contents),
        "all_contents": all_contents,
        "has_answer_contents": has_answer_contents,
    }


def run_system_mnemosis(
    question: dict, qid: str, top_k: int, workdir: str, mode: str
) -> dict:
    from mnemosis.vector_index import VectorIndex

    db_dir = os.path.join(workdir, "mnemo", qid + "_" + mode)
    os.makedirs(db_dir, exist_ok=True)
    dense_embedder = None
    vector_index = None
    if mode in ("dense", "seg"):
        cache_path = os.path.join(
            _WORK, "vectors_persist", f"{qid}_{mode}.sqlite"
        )
        dense_embedder = make_nomic_embedder(cache_path)
        index_path = os.path.join(
            _WORK, "vectors_persist", f"{qid}_{mode}_index.sqlite"
        )
        vector_index = VectorIndex(index_path)
        vector_index.clear()
    engine = MemoryEngine(
        memory_file=os.path.join(db_dir, "memory.db"),
        embedder=None if mode in ("kw", "hybrid", "seg") else NGramEmbedder(),
        vector_index=vector_index,
        index_embedder=dense_embedder,
    )
    has_answer_contents: set[str] = set()
    all_contents: set[str] = set()
    segment_source: dict[str, str] = {}
    segment_sid: dict[str, str] = {}
    sid_dates: dict[str, str] = {}
    turns = 0
    t0 = time.perf_counter()
    session_ids = question.get("haystack_session_ids") or []
    session_dates = question.get("haystack_dates") or []
    pending_records: list[dict] = []
    for s_index, session in enumerate(question["haystack_sessions"]):
        sid = (
            session_ids[s_index]
            if s_index < len(session_ids)
            else f"session{s_index}"
        )
        sdate = (
            session_dates[s_index]
            if s_index < len(session_dates)
            else ""
        )
        cues = [f"sid:{sid}"]
        if sdate:
            cues.append(f"date:{sdate}")
        sid_dates[sid] = sdate
        for turn in session:
            content = turn.get("content", "")
            if not content:
                continue
            source = SourceRecord(
                origin=SourceType.USER if turn.get("role") == "user" else SourceType.AGENT
            )
            if mode == "seg":
                for segment in segment_text(content):
                    pending_records.append(
                        {
                            "content": segment,
                            "kind": MemoryKind.EPISODIC,
                            "source": source,
                            "cues": list(cues),
                            "importance": 0.5,
                        }
                    )
                    turns += 1
                    all_contents.add(segment)
                    if turn.get("has_answer"):
                        has_answer_contents.add(segment)
                    segment_source[segment] = content
                    segment_sid[segment] = sid
            else:
                pending_records.append(
                    {
                        "content": content,
                        "kind": MemoryKind.EPISODIC,
                        "source": source,
                        "cues": list(cues),
                        "importance": 0.5,
                    }
                )
                turns += 1
                all_contents.add(content)
                if turn.get("has_answer"):
                    has_answer_contents.add(content)
    if pending_records:
        # Batch ingestion: same per-item semantics as the old loop, but term
        # rows, links and (in dense mode) embeddings are committed in bulk,
        # so 480-turn sessions ingest in seconds instead of a minute.
        engine.remember_many(pending_records)
    ingest = time.perf_counter() - t0

    t0 = time.perf_counter()
    if mode == "hybrid":
        results = engine.recall_fused(
            question["question"],
            top_k=top_k,
            pass_k=30,
            rrf_k=30,
            ng_weight=2.0,
        )
    elif mode == "dense":
        results = engine.recall_fused(
            question["question"],
            top_k=top_k,
            pass_k=30,
            rrf_k=30,
            kw_weight=0.0,
            ng_weight=0.0,
            dense_embedder=dense_embedder,
            dense_weight=1.0,
            vector_index=vector_index,
            recency_weight=0.0,
            cue_weight=0.0,
            date_weight=0.0,
        )
    elif mode == "seg":
        results = engine.recall_fused(
            question["question"],
            top_k=top_k,
            pass_k=30,
            rrf_k=30,
            kw_weight=0.5,
            ng_weight=0.0,
            dense_embedder=dense_embedder,
            dense_weight=1.0,
            vector_index=vector_index,
            recency_weight=0.0,
            cue_weight=0.0,
            date_weight=0.0,
        )
    else:
        results = engine.recall(question["question"], top_k=top_k)
    search = time.perf_counter() - t0
    contents = [r.item.content for r in results]
    engine.close()
    if vector_index is not None:
        vector_index.close()
    return {
        "turns": turns,
        "ingest_seconds": round(ingest, 2),
        "search_ms": round(search * 1000, 1),
        "contents": contents,
        "evidence_hits": sum(1 for c in contents if c in has_answer_contents or any(c in h for h in has_answer_contents)),
        "evidence_total": len(has_answer_contents),
        "all_contents": all_contents,
        "has_answer_contents": has_answer_contents,
        "segment_source": segment_source,
        "segment_sid": segment_sid,
        "sid_dates": sid_dates,
    }


def summarize(name: str, rows: list[dict]) -> dict:
    n = len(rows)
    def rate(key: str) -> float:
        return round(sum(1 for r in rows if r[key]) / n, 3) if n else 0.0

    qa_rows = [r for r in rows if not r.get("abstain")]
    abstain_rows = [r for r in rows if r.get("abstain")]
    n_qa = len(qa_rows)
    return {
        "name": name,
        "n": n,
        "turn_recall@1": rate("turn_hit1"),
        "turn_recall@5": rate("turn_hit5"),
        "turn_recall@10": rate("turn_hit10"),
        "answer_tokens@5": rate("answer_hit5"),
        "llm_accuracy": round(
            sum(1 for r in rows if r.get("llm_correct") is True) / n, 3
        ) if n else 0.0,
        "llm_accuracy_qa": round(
            sum(1 for r in qa_rows if r.get("llm_correct") is True) / n_qa, 3
        ) if n_qa else 0.0,
        "abstention_pass": round(
            sum(1 for r in abstain_rows if r.get("llm_correct") is True) / len(abstain_rows), 3
        ) if abstain_rows else None,
        "avg_ingest_seconds": round(sum(r["ingest_seconds"] for r in rows) / n, 2) if n else 0.0,
        "avg_search_ms": round(sum(r["search_ms"] for r in rows) / n, 1) if n else 0.0,
        "avg_turns": round(sum(r["turns"] for r in rows) / n, 1) if n else 0.0,
    }


def sample_questions(data: list[dict], count: int, seed: int) -> list[dict]:
    rng = random.Random(seed)
    if count <= 0:
        return []
    if count <= 8:
        return rng.sample(data, count)
    by_type: dict[str, list[dict]] = {}
    for item in data:
        by_type.setdefault(item["question_type"], []).append(item)
    picked: list[dict] = []
    per_type = max(1, count // len(by_type))
    for items in by_type.values():
        picked.extend(rng.sample(items, min(per_type, len(items))))
    remaining = count - len(picked)
    if remaining > 0:
        pool = [x for x in data if x not in picked]
        picked.extend(rng.sample(pool, min(remaining, len(pool))))
    return picked


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True)
    parser.add_argument("--questions", type=int, default=20)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--top-k", type=int, default=10)
    parser.add_argument("--local-questions", type=int, default=12)
    parser.add_argument("--skip-mem0", action="store_true")
    parser.add_argument("--skip-mnemosis", action="store_true")
    parser.add_argument("--skip-answers", action="store_true")
    parser.add_argument(
        "--cloud-answers",
        action="store_true",
        help="use cloud Qwen for answers (default: local-only)",
    )
    parser.add_argument(
        "--modes",
        default="kw,ngram,hybrid,dense",
        help="comma-separated Mnemosis modes to run",
    )
    parser.add_argument(
        "--out",
        default=os.path.join(_BENCH, "results", "longmemeval_s_compare.json"),
    )
    args = parser.parse_args()

    print("loading dataset ...", flush=True)
    with open(args.data, encoding="utf-8") as handle:
        data = json.load(handle)
    questions = sample_questions(data, args.questions, args.seed)
    print(
        f"questions: {len(questions)} | types: {dict(Counter(q['question_type'] for q in questions))}",
        flush=True,
    )

    systems = []
    if not args.skip_mem0:
        systems.append("mem0")
    if not args.skip_mnemosis:
        for mode in (m.strip() for m in args.modes.split(",")):
            if mode:
                systems.append(f"mnemosis_{mode}")

    rows: dict[str, list[dict]] = {s: [] for s in systems}
    completed_by_system: dict[str, set[str]] = {
        name: set() for name in systems
    }
    if os.path.exists(args.out):
        with open(args.out, encoding="utf-8") as handle:
            old = json.load(handle)
        if "rows" in old:
            rows = old["rows"]
            for name in systems:
                rows.setdefault(name, [])
            completed_by_system = {
                name: {row["qid"] for row in rows.get(name, [])}
                for name in systems
            }
            total_done = sum(len(v) for v in completed_by_system.values())
            print(f"resume: {total_done} system-question rows already done",
                  flush=True)

    workdir = os.path.join(_WORK, "longmemeval_run")
    if not any(completed_by_system.values()) and os.path.isdir(workdir):
        shutil.rmtree(workdir)
    os.makedirs(workdir, exist_ok=True)

    for qi, question in enumerate(questions, 1):
        qid = question["question_id"]
        pending = [
            name for name in systems if qid not in completed_by_system[name]
        ]
        if not pending:
            print(f"[{qi}/{len(questions)}] skip {qid} (already done)", flush=True)
            continue
        q = question["question"]
        gold = str(question["answer"])
        gold_lower = gold.lower().strip()
        abstain = any(
            keyword in gold_lower
            for keyword in (
                "unknown", "not mentioned", "not available", "n/a",
                "unable to answer", "cannot be determined", "not discussed",
                "no information",
            )
        )
        print(
            f"[{qi}/{len(questions)}] {qid} {question['question_type']} "
            f"sessions={len(question['haystack_sessions'])}",
            flush=True,
        )
        per_system: dict[str, dict] = {}
        runners: list[tuple[str, object]] = []
        if "mem0" in pending:
            runners.append(
                (
                    "mem0",
                    lambda question=question, qid=qid: run_system_mem0(
                        question, qid, args.top_k, workdir
                    ),
                )
            )
        for mode in ("kw", "ngram", "hybrid", "dense", "seg"):
            name = f"mnemosis_{mode}"
            if name in pending:
                runners.append(
                    (
                        name,
                        lambda mode=mode, question=question, qid=qid: (
                            run_system_mnemosis(
                                question, qid, args.top_k, workdir, mode
                            )
                        ),
                    )
                )
        for name, runner in runners:
            try:
                run = runner()
                per_system[name] = run
                detail = (
                    f" turns={run['turns']}"
                    if name in ("mem0", "mnemosis_seg")
                    else ""
                )
                print(
                    f"  {name} ingest={run['ingest_seconds']}s{detail}",
                    flush=True,
                )
            except Exception as exc:  # noqa: BLE001
                print(f"  {name} failed: {exc}", flush=True)

        expected = _tokens(gold)
        for name, run in per_system.items():
            contents = run["contents"]
            top1 = contents[:1]
            top5 = contents[:5]
            top10 = contents[:10]
            def evidence_in(cands: list[str], has: set[str]) -> bool:
                return any(c in has or any(c in h for h in has) for c in cands)
            row = {
                "qid": qid,
                "question_type": question["question_type"],
                "question": q,
                "gold": gold,
                "abstain": abstain,
                "turns": run["turns"],
                "ingest_seconds": run["ingest_seconds"],
                "search_ms": run["search_ms"],
                "turn_hit1": evidence_in(top1, run["has_answer_contents"]),
                "turn_hit5": evidence_in(top5, run["has_answer_contents"]),
                "turn_hit10": evidence_in(top10, run["has_answer_contents"]),
                "answer_hit5": bool(expected) and any(
                    _answer_hit(c, expected) for c in top5
                ),
                "answer_hit1": bool(expected) and any(
                    _answer_hit(c, expected) for c in top1
                ),
                "context": top5,
            }
            rows[name].append(row)

        if not args.skip_answers:
            local_now = qi <= args.local_questions
            for name, run in per_system.items():
                answer_ctx = list(run["contents"][:10])
                if run.get("segment_source"):
                    for segment in list(answer_ctx)[:5]:
                        source_turn = run["segment_source"].get(segment)
                        if (
                            source_turn
                            and source_turn not in answer_ctx
                            and len(answer_ctx) < 14
                        ):
                            answer_ctx.append(source_turn)
                    sid_dates = run.get("sid_dates") or {}
                    segment_sid = run.get("segment_sid") or {}
                    dated = []
                    for item in answer_ctx:
                        date = sid_dates.get(segment_sid.get(item, ""), "")
                        if date:
                            dated.append(f"[{date}] {item}")
                        else:
                            dated.append(item)
                    answer_ctx = dated
                rows[name][-1]["context"] = answer_ctx
                if args.cloud_answers:
                    prompt = answer_prompt(answer_ctx, q)
                    cloud_ans = _cloud_with_retry(prompt, max_tokens=300)
                    llm_correct = judge_answer(q, gold, cloud_ans)
                    rows[name][-1]["llm_answer"] = cloud_ans
                    rows[name][-1]["llm_correct"] = llm_correct
                    rows[name][-1]["local_answer"] = None
                    rows[name][-1]["local_correct"] = None
                    print(f"    [{name}] cloud judge={llm_correct}", flush=True)
                else:
                    prompt = answer_prompt_local(
                        answer_ctx, q, question.get("question_date", "")
                    )
                    gemma_ans = _local_with_retry(
                        prompt, model=STRONG_LOCAL_MODEL
                    )
                    qwen_ans = _local_with_retry(prompt, model=LOCAL_MODEL)
                    gemma_correct = judge_local_strict(q, gold, gemma_ans)
                    qwen_correct = judge_local_strict(q, gold, qwen_ans)
                    rows[name][-1]["llm_answer"] = gemma_ans
                    rows[name][-1]["llm_correct"] = gemma_correct
                    rows[name][-1]["local_answer"] = qwen_ans
                    rows[name][-1]["local_correct"] = qwen_correct
                    rows[name][-1]["keyword_correct"] = keyword_correct(
                        q, gold, gemma_ans
                    )
                    print(
                        f"    [{name}] gemma={gemma_correct} "
                        f"qwen={qwen_correct}",
                        flush=True,
                    )
                if args.cloud_answers and local_now:
                    try:
                        local_ans = _local_with_retry(prompt)
                        rows[name][-1]["local_answer"] = local_ans
                        rows[name][-1]["local_correct"] = judge_answer(q, gold, local_ans)
                        print(f"    [{name}] local judge={rows[name][-1]['local_correct']}",
                              flush=True)
                    except Exception as exc:  # noqa: BLE001
                        print(f"    [{name}] local failed: {exc}", flush=True)
        else:
            for name in per_system:
                rows[name][-1]["llm_answer"] = None
                rows[name][-1]["llm_correct"] = None
                rows[name][-1]["local_answer"] = None
                rows[name][-1]["local_correct"] = None

        summary = {name: summarize(name, rows[name]) for name in systems}
        os.makedirs(os.path.dirname(args.out), exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as handle:
            json.dump({"summary": summary, "rows": rows, "partial": True},
                      handle, ensure_ascii=False, indent=2)
        done_rows = sum(len(v) for v in rows.values())
        print(f"  saved partial ({done_rows} rows)", flush=True)

    summary = {name: summarize(name, rows[name]) for name in systems}
    report = {"summary": summary, "rows": rows}
    with open(args.out, "w", encoding="utf-8") as handle:
        json.dump(report, handle, ensure_ascii=False, indent=2)
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print(f"\nsaved: {args.out}")
    return 0


