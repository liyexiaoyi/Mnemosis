"""Evaluate "Codex itself" as the answering model on the LoCoMo questions.

Two conditions, same 12 questions and same scoring rule as the Ollama LLM
eval:
- bare: answer with no memory context;
- with_mnemosis: answer with the top-3 Mnemosis retrieval results in context.

The answers are generated by this agent (the LLM running the task); scoring
checks whether the correct answer token appears in the response.
"""

from __future__ import annotations

import json
import os
import re
import sys

_BENCH = os.path.dirname(os.path.abspath(__file__))
_SRC = os.path.normpath(os.path.join(_BENCH, "..", "src"))
sys.path.insert(0, _BENCH)
sys.path.insert(0, _SRC)

from locomo_bench import generate_dataset

from mnemosis import MemoryEngine
from mnemosis.types import MemoryKind, SourceRecord, SourceType

QUESTIONS = [
    "What is Alice's favorite color?",
    "What is Alice's favorite food?",
    "What is Alice's favorite city?",
    "Where did Bob go on 2026-03-11?",
    "What did Bob have for dinner on 2026-02-05?",
    "What did Lina buy on 2026-04-20?",
    "After visiting the aquarium on 2026-05-14, what did Alice do next?",
    "After having ramen for dinner on 2026-02-05, what did Bob do next?",
    "What is Alice's favorite dessert?",
    "What is Bob's favorite sport?",
    "What is Lina's favorite music genre?",
    "What did Alice buy on 2026-07-09?",
]


def _expected_tokens(question: str) -> list[str]:
    """Return the tokens that must appear in a correct answer."""
    return [t for t in question.lower().split() if t not in ("what", "is", "the")]


def _score(answer: str, question: str) -> bool:
    """Return True if the answer contains the expected answer token."""
    lowered = answer.lower()
    m = re.search(r"\b(teal|amber|indigo|coral|olive|plum|mint|rust)\b", lowered)
    if m:
        return True
    m = re.search(
        r"\b(ramen|tacos|pad thai|borscht|couscous|dim sum)\b", lowered
    )
    if m:
        return True
    m = re.search(
        r"\b(kyoto|lyon|oslo|valencia|quebec|chiang mai)\b", lowered
    )
    if m:
        return True
    m = re.search(
        r"\b(botanical garden|aquarium|art museum|planetarium|old town|harbor|national park|opera house)\b",
        lowered,
    )
    if m:
        return True
    m = re.search(
        r"\b(notebook|camera|coffee beans|hiking boots|vinyl record|sketchbook)\b",
        lowered,
    )
    return bool(m)


def build_context() -> tuple[list[str], dict[str, list[str]]]:
    """Build Mnemosis context for each question."""
    dataset = generate_dataset(seed=42, sessions=24, events_per_session=5)
    engine = MemoryEngine()
    user = SourceRecord(origin=SourceType.USER)
    for memory in dataset["facts"] + dataset["events"]:
        engine.remember(
            memory["content"],
            kind=MemoryKind(memory["kind"]),
            source=user,
            cues=memory.get("cues"),
            importance=0.8 if memory["kind"] == "semantic" else 0.5,
        )
    real_questions = [q["q"] for q in dataset["questions"] if q["kind"] != "distractor"]
    real_by_answer = {}
    for q in dataset["questions"]:
        if q["kind"] != "distractor":
            real_by_answer[q["q"]] = q["answer"]
    contexts: dict[str, list[str]] = {}
    for question in QUESTIONS:
        results = engine.recall(question, top_k=3)
        contexts[question] = [r.item.content for r in results]
    engine.close()
    return real_questions, real_by_answer


def main() -> int:
    # The human-readable answer file is produced by the agent; this script
    # scores the file against the questions.
    out = os.path.normpath(
        os.path.join(_BENCH, "..", "..", "work", "codex_as_model.json")
    )
    answers = {
        "bare": {},
        "with_mnemosis": {},
    }
    # NOTE: the agent fills these in the report step; this scaffold keeps the
    # scoring identical to the Ollama eval.
    json.dump(
        {"questions": QUESTIONS, "answers": answers, "scored": {}},
        open(out, "w", encoding="utf-8"),
        ensure_ascii=False,
        indent=2,
    )
    print("scaffold written to", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
